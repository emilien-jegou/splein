// Single responsibility: lower the material IR to a WGSL `apply` module.
//
// This is the single lowering path (D-M6): the `view!` material form
// calls this at expansion time; there is no runtime interpreter to
// drift. Output = the custom `apply` module the engine composes as
// `EFFECT_ABI_WGSL + apply + ENGINE_ENTRY_WGSL` (see `renderer.rs`
// `custom_pipeline_for`). Reads textures only through
// `textureSampleLevel(_, 0.0)` (non-uniform control flow, D-M7).
//
// Scope — Phase 1 (v1 core subset):
//   * `Normal::Flat` only (the `(0,0,1)` baseline; every other normal
//     constructor is Phase 2a and rejected loudly here).
//   * Closures: `Ggx` (+ optional `Sky` env gain); `Refract` rejected
//     (Phase 2a — needs displaced backdrop reads + frost blur).
//   * Modulators: `Color`, `Intensity`; `Beer` rejected (Phase 2c —
//     needs `path_length`), `ThinFilm` rejected (Phase 3).
//   * Weights: `Fresnel` (Schlick off `n.z`, view `(0,0,1)`) and
//     `Scalar`; everything sums/mixes straight-line.
//   * Extended closures (`Beckmann`, `Anisotropic`, `Conductor`,
//     `Sheen`, `Burley`, `EmissionGrid`) rejected (Phase 3).
//
// Every rejection is a compile error naming the phase, never a silent
// mis-lowering (risks §5: the macro must reject the subset loudly).
//
// Uniform layout: slots in arena order, packed into `CustomUniforms`
// (`data: array<vec4<f32>, 8>`, 32 f32s). `u slot N` reads
// `data[N/4][N%4]` — generated by `uniform_ref`.

use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::Result as SynResult;

use crate::material_ir::{Closure, Env, MaterialExpr, Modulator, Normal, Value, Weight};

/// WGSL read of uniform slot `N` in the engine's `CustomUniforms` layout
/// (`data: array<vec4<f32>, 8>`; engine pads the stage's uniforms to the
/// full 32 f32s — see `run_custom_pass`).
fn uniform_ref(slot: u32) -> String {
    format!("u.data[{}][{}]", slot / 4, slot % 4)
}

/// A numeric value as WGSL: literals inline (`0.35`); slots read the
/// uniform block.
fn value_wgsl(v: &Value) -> String {
    match v {
        Value::Lit(f) => {
            // WGSL needs a decimal point or explicit f32 suffix for
            // floats; `{f:?}` keeps full precision (`1.0`, not `1`).
            format!("{f:?}")
        }
        Value::Slot { slot } => uniform_ref(*slot),
    }
}

/// Normal field as a WGSL `vec3<f32>` expression. Phase 1: `Flat` only.
fn normal_wgsl(n: &Normal) -> SynResult<String> {
    match n {
        Normal::Flat => Ok("vec3<f32>(0.0, 0.0, 1.0)".to_string()),
        other => Err(syn::Error::new(
            proc_macro2::Span::call_site(),
            format!(
                "material DSL (Phase 1): {other:?} normals lower in Phase 2a — \
                 only `Normal::flat()` is available yet"
            ),
        )),
    }
}

/// Environment gain as a WGSL scalar. `None` = the unit ambient (1.0).
fn env_gain_wgsl(env: Option<&Env>) -> String {
    match env {
        None => "1.0".to_string(),
        Some(e) => value_wgsl(&e.gain),
    }
}

/// One closure evaluated at `px`, returning a WGSL `vec3<f32>` radiance
/// expression. `env_wgsl` is the precomputed environment gain for the
/// enclosing term (`Lit` node or unit ambient).
fn closure_wgsl(c: &Closure, env_wgsl: &str) -> SynResult<String> {
    match c {
        Closure::Ggx { normal, roughness } => {
            let n = normal_wgsl(normal)?;
            let a = value_wgsl(roughness);
            // Isotropic GGX specular against the environment (the
            // reference formula the glass `ggx.wgsl` stage uses, reduced
            // to the flat-normal material form): Schlick Fresnel at
            // F0 = 0.04 times the NDF lobe, scaled by the env gain.
            Ok(format!(
                "(ggx_spec(vec3<f32>(0.0, 0.0, 1.0), ({n}), ({a})) * ({env_wgsl}))"
            ))
        }
        Closure::Refract { .. } => Err(syn::Error::new(
            proc_macro2::Span::call_site(),
            "material DSL (Phase 1): `Refract` lowers in Phase 2a \
             (displaced backdrop reads + frost blur) — \
             use `Microfacet::ggx` / `Sky` / `Color` until then",
        )),
        other => Err(syn::Error::new(
            proc_macro2::Span::call_site(),
            format!(
                "material DSL (Phase 1): {other:?} lowers in Phase 3 \
                 (extended closures) — core set is ggx + refract/frost/normals (2a/2b)"
            ),
        )),
    }
}

/// Modulator applied to an inner term expression.
fn modulator_wgsl(m: &Modulator, inner: &str) -> SynResult<String> {
    match m {
        Modulator::Color { r, g, b } => {
            let (r, g, b) = (value_wgsl(r), value_wgsl(g), value_wgsl(b));
            Ok(format!(
                "(vec3<f32>(({r}), ({g}), ({b})) * ({inner})))"
            ))
        }
        Modulator::Intensity { lumens } => {
            let k = value_wgsl(lumens);
            Ok(format!("((({inner})) * ({k}))"))
        }
        Modulator::Beer { .. } => Err(syn::Error::new(
            proc_macro2::Span::call_site(),
            "material DSL (Phase 1): `Absorption::beer` lowers in Phase 2c \
             (needs `path_length` from displaced reads)",
        )),
        Modulator::ThinFilm { .. } => Err(syn::Error::new(
            proc_macro2::Span::call_site(),
            "material DSL (Phase 1): `ThinFilm::interference` lowers in \
             Phase 3 (extended closures)",
        )),
    }
}

/// Blend weight as a WGSL scalar.
fn weight_wgsl(w: &Weight) -> SynResult<String> {
    match w {
        Weight::Scalar(v) => Ok(format!("({})", value_wgsl(v))),
        Weight::Fresnel { normal, ior } => {
            let n = normal_wgsl(normal)?;
            let ior = value_wgsl(ior);
            // Schlick off `n.z` (view `(0,0,1)`):
            // `F0 = ((ior-1)/(ior+1))^2`, `F = F0 + (1-F0)(1-NoV)^5`.
            Ok(format!(
                "(fresnel_schlick(({n}).z, ({ior})))"
            ))
        }
    }
}

/// The term as a WGSL `vec3<f32>` radiance expression.
fn term_wgsl(expr: &MaterialExpr) -> SynResult<String> {
    match expr {
        MaterialExpr::Closure(c) => closure_wgsl(c, "1.0"),
        MaterialExpr::Lit(c, env) => closure_wgsl(c, &env_gain_wgsl(Some(env))),
        MaterialExpr::Modulated(m, inner) => {
            let inner = term_wgsl(inner)?;
            modulator_wgsl(m, &inner)
        }
        MaterialExpr::Sum(a, b) => {
            let (a, b) = (term_wgsl(a)?, term_wgsl(b)?);
            Ok(format!("(({a}) + ({b}))"))
        }
        MaterialExpr::Mix(a, b, w) => {
            let (a, b, w) = (term_wgsl(a)?, term_wgsl(b)?, weight_wgsl(w)?);
            Ok(format!("mix(({a}), ({b}), ({w}))"))
        }
    }
}

/// Shared WGSL helpers every lowered module prefixes (Schlick + the
/// flat-normal GGX specular lobe; the port of the `ggx.wgsl` reference
/// formula to the material's `(N, roughness)` inputs).
const PRELUDE_WGSL: &str = r#"
fn fresnel_schlick(nov: f32, ior: f32) -> f32 {
    let f0 = (ior - 1.0) / (ior + 1.0);
    let f0_2 = f0 * f0;
    let t = clamp(1.0 - nov, 0.0, 1.0);
    return f0_2 + (1.0 - f0_2) * t * t * t * t * t;
}

fn ggx_spec(v: vec3<f32>, n: vec3<f32>, roughness: f32) -> vec3<f32> {
    let a = max(roughness, 0.001);
    let a2 = a * a;
    let nov = max(dot(n, v), 0.0);
    let d = (a2 - 1.0) * nov * nov + 1.0;
    let ndf = a2 / (3.14159265 * d * d);
    let f0 = vec3<f32>(0.04);
    let f = f0 + (vec3<f32>(1.0) - f0) * pow(1.0 - nov, 5.0);
    return f * ndf * nov;
}
"#;

/// Lower the tree to the complete custom `apply` module source: the
/// library prefix (`PRELUDE_WGSL`) + the straight-line `apply` whose
/// body evaluates the expression and outputs it as opaque surface color
/// (silhouette coverage from the host's `ctx.coverage`; the backdrop
/// enters only through `Refract`, which Phase 1 rejects — so Phase 1
/// surfaces are opaque plaques per the opacity rule, §1.3).
pub fn lower_to_apply(expr: &MaterialExpr) -> SynResult<String> {
    let radiance = term_wgsl(expr)?;
    Ok(format!(
        "{PRELUDE_WGSL}\nfn apply(\n    ctx: EffectCtx,\n    backdrop: texture_2d<f32>,\n    sharp: texture_2d<f32>,\n    u: CustomUniforms,\n) -> EffectCtx {{\n    var out = ctx;\n    let radiance: vec3<f32> = {radiance};\n    out.color = vec4<f32>(radiance * ctx.coverage, ctx.coverage);\n    return out;\n}}\n"
    ))
}

/// The lowered module plus its uniform-slot count (arena length): the
/// macro emits the source as `&'static str`, the count sizes the filler.
pub struct Lowered {
    pub source: String,
    pub uniform_slots: u32,
}

/// Hash the source for the pipeline-cache key input (D-M5: cache keyed
/// on generated WGSL source — a compile-time constant).
pub fn source_hash(source: &str) -> u64 {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in source.as_bytes() {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

/// Emit the runtime construction tokens for a lowered surface: a
/// `CustomEffect` whose WGSL is the static source and whose uniforms
/// vector the filler writes in arena order. `filler` is the per-slot
/// write expressions (`slot 0 <- <runtime expr>`, ...).
pub fn emit_surface_tokens(source: &str, filler: &[TokenStream2]) -> TokenStream2 {
    quote! {
        ::riode::foundation::CustomEffect::new(
            #source,
            ::std::vec![#(#filler),*],
            ::riode::foundation::BackdropNeed::None,
        )
    }
}
